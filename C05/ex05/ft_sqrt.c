int	ft_sqrt(int nb)
{
	long	res;
	int		i;

	if (nb == 1)
		return (1);
	if (nb <= 0)
		return (0);
	i = 1;
	while (i <= nb / i)
	{
		res = (i * i);
		if (res == nb)
			return (i);
		i++;
	}
	return (0);
}
